#!/usr/bin/env python3
"""Phase 1, item 1: early / middle / late final-stage checkpoints per training seed by a FIXED
iteration rule. Reads only the checkpoint listing, each seed's stages.json (stage boundaries) and
the checkpoint files themselves (hash, metadata, actor digest). It reads no evaluation result
(no gate, held-out or curve rate), so the choice cannot depend on validation performance.

Rule (fixed before this script ran; docs/PREFILTER_VALIDATION_PROTOCOL_DRAFT_2026-10-25.md):
  n      = iterations of the final curriculum stage (stage 4, densities 2/5/8)
           = ceil(stage budget 8,000,000 env steps / 24,576 env steps per iteration) = 326
  r(c)   = final-stage iteration of checkpoint c = c.iteration - (first final-stage iteration - 1)
  early  = saved final-stage checkpoint with the smallest r >= ceil(n/3)    (= 109)
  middle = saved final-stage checkpoint with the smallest r >= ceil(2n/3)   (= 218)
  late   = the final-stage checkpoint with r = n (end of the stage budget)
Checkpoints are saved every 20 final-stage iterations and at r = n, so the rule gives r = 120,
220, 326 for every seed. No other checkpoint is a candidate; the best of the 51 is not chosen.

Writes results/phase1/checkpoint_selection.json and .md."""
import hashlib, json, math, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def main():
    from cbf_study.config import StudyConfig
    from cbf_study.policies import FrozenMAPPOPolicy
    cfg = StudyConfig.load()
    cur = cfg.curriculum()
    env_steps_per_it = cur["envs_per_iter"] * int(cfg.mappo["rollout_steps"])
    n = math.ceil(cur["budget"][-1] / env_steps_per_it)
    targets = dict(early=math.ceil(n / 3), middle=math.ceil(2 * n / 3), late=n)
    out = dict(rule=dict(
        text="final stage only; r = final-stage iteration; early = first saved checkpoint with r >= ceil(n/3), "
             "middle = first with r >= ceil(2n/3), late = r = n (end of the final-stage budget)",
        n_final_stage_iterations=n, env_steps_per_iteration=env_steps_per_it, final_stage_budget=cur["budget"][-1],
        r_thresholds=targets, inputs="checkpoint file names, stages.json stage boundaries, checkpoint files; "
                                     "no evaluation result is read"),
        env_fingerprint=cfg.env_fingerprint(), policies=[])
    for seed in cfg.mappo["seeds"]:
        d = ROOT / "results" / "curriculum" / f"seed_{seed}"
        stages = json.loads((d / "stages.json").read_text())["stages"]
        final = stages[-1]
        assert final["stage"] == len(cur["stages"]) - 1 and final["iterations"] == n, (seed, final)
        first_it = sum(s["iterations"] for s in stages[:-1]) + 1
        ckpts = {int(re.search(r"ckpt_it(\d+)", p.name).group(1)): p for p in sorted((d / "checkpoints").glob("ckpt_it*.pt"))}
        r_of = {it - (first_it - 1): it for it in ckpts if it >= first_it}
        for name, t in targets.items():
            r = n if name == "late" else min(x for x in r_of if x >= t)
            assert r in r_of, (seed, name, r)
            it = r_of[r]
            pol = FrozenMAPPOPolicy(ckpts[it], cfg)
            prov = "original run"
            if seed == 1 and it > 546:
                prov = "resumed run (seed 1 resumed from its saved iteration-546 state; audit/PROVENANCE.md section 3)"
            out["policies"].append(dict(
                policy_id=f"s{seed}_{name}", seed=seed, phase=name, final_stage_iteration=r, iteration=it,
                env_steps=int(pol.meta["env_steps"]), ckpt=str(ckpts[it].relative_to(ROOT)), ckpt_sha256=sha256(ckpts[it]),
                actor_param_digest=pol.digest, provenance=prov))
    (ROOT / "results" / "phase1" / "checkpoint_selection.json").write_text(json.dumps(out, indent=1))
    L = ["# Phase 1: checkpoint selection rule and IDs", "",
         "Generated by `scripts/phase1_select_checkpoints.py`, which reads only file names, stage boundaries and "
         "checkpoint files (no evaluation result).", "",
         f"Rule: final curriculum stage only (densities 2/5/8, budget {cur['budget'][-1]:,} env steps = n = {n} iterations "
         f"of {env_steps_per_it:,} env steps). With r the final-stage iteration: early = first saved checkpoint with "
         f"r >= ceil(n/3) = {targets['early']}; middle = first with r >= ceil(2n/3) = {targets['middle']}; "
         f"late = r = n = {n}.", "",
         "| policy | seed | phase | final-stage iteration r | global iteration | env steps | checkpoint | SHA-256 (file) | actor digest | provenance |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for p in out["policies"]:
        L.append(f"| {p['policy_id']} | {p['seed']} | {p['phase']} | {p['final_stage_iteration']} | {p['iteration']} | "
                 f"{p['env_steps']:,} | `{p['ckpt']}` | `{p['ckpt_sha256'][:16]}…` | `{p['actor_param_digest'][:16]}…` | {p['provenance']} |")
    (ROOT / "results" / "phase1" / "checkpoint_selection.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Writes results/final_test/INFEASIBILITY_AUDIT.md (EXPLORATORY, POST HOC) from the CSV/JSON
outputs of scripts/infeasibility_audit.py."""
import csv, json, sys
from collections import Counter
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from cbf_study.config import StudyConfig      # noqa: E402

D = ROOT / "results" / "final_test" / "infeasibility"
S = json.loads((D / "summary.json").read_text())
R = list(csv.DictReader(open(D / "infeasible_robots.csv")))
T = list(csv.DictReader(open(D / "infeasible_trials.csv")))
I = [r for r in csv.DictReader(open(D / "initial_state_negative_barriers.csv")) if r.get("source")]
cfg = StudyConfig.load()
fc = cfg.filter_config(10.0)
sc = cfg.scenario_config()
excl = sc.edge_clear + fc.d_obst + sc.slot_radius
q = lambda k, rs=R: np.percentile([float(r[k]) for r in rs], [0, 10, 50, 90, 100])
fmt = lambda v, p=2: " / ".join(f"{x:.{p}e}" for x in v)
rep = [r for r in R if r["reproduced"] == "1"]
near = sum(r["near_boundary_diagnostic"] == "1" for r in rep)
sign_flip = sum(np.sign(float(r["binding_zero_slack_f32"])) != np.sign(float(r["binding_zero_slack_f64"])) for r in rep)
L = ["# Infeasibility audit of the final test (EXPLORATORY, POST HOC)", "",
     "**EXPLORATORY, POST HOC.** Saved per-step logs, saved layouts and saved validation arrays only; no simulation, no "
     "environment stepping, no new layouts; no outcome is relabelled and no confirmatory number changes. Generated by "
     "`scripts/infeasibility_audit.py` (computation) and `scripts/infeasibility_audit_md.py` (this file); tables in "
     "`results/final_test/infeasibility/`.", "",
     "## (a) The 433 filter-on INFEASIBLE trials", "",
     "**Method.** For each trial the saved pre-step state of the attempted period (which infeasibility prevented) and the saved "
     "raw actor command. Reproduction: the unchanged `CBFQPFilter` at alpha* = 10 was called once on these saved values (the "
     "code promotes the logged float32 values to float64, so 'logged dtype' and 'float64' inputs coincide on this code path); "
     "its verdict was only compared with the logged one. Rows were rebuilt with the identical construction "
     "(`bmatch.barrier_rows`) in float64, and independently in float32 arithmetic. Normalised slack = (a.u - b)/|a| (negative "
     "= violated; solver tolerance 1e-9). Stand-off h* = row margin / row gain (obstacle delta_o/alpha; pair (delta_ij/2)/(alpha/2)). "
     "Binding row = the enabled row of an infeasible robot with the most negative zero-command slack.", "",
     f"**Reproduction: {S['reproduced']} of {S['infeasible_trials']} trials** ({S['reproduced_robots']} of {S['infeasible_robots']} "
     "infeasible robots) are reproduced as infeasible by the recomputation, with the same infeasible robots. Every infeasible "
     "trial has exactly one infeasible robot.", "",
     "| quantity (reproduced robots) | min / p10 / median / p90 / max |", "|---|---|",
     f"| binding row: zero-command slack, float64 | {fmt(q('binding_zero_slack_f64', rep))} |",
     f"| binding row: zero-command slack, float32 arithmetic | {fmt(q('binding_zero_slack_f32', rep))} |",
     f"| binding row: slack of the clipped nominal command | {fmt(q('binding_nominal_slack_f64', rep))} |",
     f"| binding row: barrier value h [m^2] | {fmt(q('binding_h', rep), 4)} |",
     f"| binding row: h - h* [m^2] | {fmt(q('binding_h_minus_hstar', rep))} |",
     f"| rows violated by the zero command (count) | {' / '.join(f'{x:.0f}' for x in q('n_rows_zero_violated', rep))} |", "",
     f"* Binding row type: " + ", ".join(f"{k} {v}" for k, v in Counter(r["binding_row"] for r in rep).most_common()) + ".",
     f"* Enabled rows of the infeasible robot (obstacle, neighbour): " + ", ".join(f"({k[0]}, {k[1]}) {v}" for k, v in
       Counter((r["enabled_obstacle_rows"], r["enabled_neighbour_rows"]) for r in rep).most_common()) + ".",
     "* Infeasible trials per density: " + ", ".join(f"K = {k}: {v}" for k, v in sorted(Counter(t["density"] for t in T).items())) + ".",
     f"* The float32-arithmetic zero-command slack of the binding row has the opposite sign to the float64 value in "
     f"{sign_flip} of {len(rep)} robots.", "",
     f"**Declared near-boundary diagnostic** (fixed before computing): |zero-command slack of the binding row| <= 1e-6 AND "
     f"|h - h*| <= 1e-3 m^2. Met by **{near} of {len(rep)}** reproduced infeasible robots. The remaining {len(rep) - near} miss "
     "only the slack threshold (their slack lies between -5e-6 and -1e-6; h - h* is below 1e-7 m^2 for all).", "",
     "**Reading.** Every reproduced infeasible state has its binding row at the stand-off h* to within about 4e-8 m^2, with the "
     "zero command violating that row by between 8e-9 and 5e-6 (normalised), and float32 rounding of the same formulas changing "
     "the sign in about a fifth of cases. This is **consistent with numerical sensitivity near the boundary**: with alpha*.dt = 1 "
     "the decay term can bring a barrier to its stand-off in about one period, after which the zero command sits within "
     "rounding of the row. It is not proof of the cause; in particular it does not show that a tolerance rule would remove "
     "the events or what the robots would then do.", "",
     "## (b) Initial states and assumption A5 (every barrier h >= 0 at t = 0)", "",
     "Checked: all 27,000 final-test trials (initial poses from the saved per-step logs, equal to the saved layout arrays) and "
     "the saved validation arrays `audit/layouts_HEAD/validation_K{0,1,2,3,5,8}_n200.npz` (1,200 layouts). **Not computable from "
     "saved data:** validation K = 4 (its layouts were generated in Phase 1 but not saved) - not checked.", "",
     "| source | layouts checked | with a negative cover barrier at t = 0 |", "|---|---|---|"]
for k, v in S["initial_state_totals"].items():
    src, K = k.rsplit("_K", 1)
    n = sum(1 for r in I if r["source"].startswith(src.replace("_", " ").split()[0]) and r["density"] == K)
    L.append(f"| {src.replace('_', ' ')}, K = {K} | {v} | {n} |")
L += [""]
for r in I:
    L += [f"**{r['policy_id']}, K = {r['density']}, trial {r['trial']}** ({r['source']}): min obstacle cover barrier "
          f"h_o = {float(r['min_h_obst']):.5f} m^2 at t = 0 (body surface gap to that obstacle {float(r['min_body_gap_obst']):.4f} m; "
          f"min robot-robot body gap {float(r['min_body_gap_rr']):.4f} m; robot-robot barriers non-negative). The nearest obstacle "
          f"centre is {float(r['obst_to_start_centroid']):.4f} m from the nominal start centroid, just beyond the sampler's exclusion "
          f"radius edge_clear + D_o + slot_radius = {excl:.2f} m.", ""]
L += ["**Likely cause** (from the sampler code, `scenario.sample_layout`; not modified): obstacle placement is checked against "
      "the NOMINAL start centroid (distance >= edge_clear + D_o + slot_radius), while the start poses carry position noise "
      f"(sigma = {sc.start_xy_std} m) and heading noise (sigma = {sc.start_th_std} rad) that move the robots' barrier points; only "
      "robot-robot barrier-point spacing is checked on the noisy poses. A robot's noisy barrier point can therefore start inside "
      "an obstacle cover disc although its body is clear. **Recorded as an A5 exception** (1 of 27,000 final-test trials; 0 of the "
      "1,200 saved validation layouts). Neither Lemma 1 nor any filter-on statement covers that start; the trial is kept "
      "unchanged in every confirmatory number.", ""]
(ROOT / "results" / "final_test" / "INFEASIBILITY_AUDIT.md").write_text("\n".join(L) + "\n")
print("ok")

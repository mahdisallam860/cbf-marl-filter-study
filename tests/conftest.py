# Neither reserved block (final test 4,000,000-4,999,999; method study 5,000,000-5,999,999) may be
# generated by any test: every reference to the layout sampler refuses a seed in those ranges.
RESERVED_BLOCKS = ((4_000_000, 4_999_999), (5_000_000, 5_999_999))


@pytest.fixture(autouse=True)
def _refuse_reserved_layout_seeds(monkeypatch):
    import cbf_study.evaluate as ev
    import cbf_study.scenario as sc
    import cbf_study.stress as stress
    import cbf_study.train_env as te
    orig = sc.sample_layout

    def guarded(seed, *a, **k):
        if any(lo <= int(seed) <= hi for lo, hi in RESERVED_BLOCKS):
            raise AssertionError(f"test tried to generate a reserved layout seed {seed}")
        return orig(seed, *a, **k)
    for mod in (sc, ev, stress, te):
        monkeypatch.setattr(mod, "sample_layout", guarded)
